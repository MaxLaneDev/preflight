import {spawn} from 'node:child_process';
import fs from 'node:fs';
const [seconds,log,command,...args]=process.argv.slice(2);
const fd=fs.openSync(log,'a');
const child=spawn(command,args,{stdio:['ignore',fd,fd]});
let expired=false;
const timer=setTimeout(()=>{expired=true;child.kill('SIGTERM');setTimeout(()=>child.kill('SIGKILL'),5000).unref();},Number(seconds)*1000);
for(const signal of ['SIGINT','SIGTERM','SIGHUP'])process.on(signal,()=>child.kill(signal));
child.on('error',e=>{clearTimeout(timer);console.error(e.message);process.exitCode=1;});
child.on('exit',(code,signal)=>{clearTimeout(timer);fs.closeSync(fd);if(expired)console.error('Timed out; inspect '+log);process.exitCode=expired?124:(code??(signal?1:0));});
